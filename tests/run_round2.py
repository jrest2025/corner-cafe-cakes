        r = await box(pg, '.ccs-more-row .ccs-link')
        check('order screen: Add note is a 44 pixel tap area', r and r[4] >= 44, r)
        await ctx.close()
        ctx, pg, errs = await newpage(b, vp={'width': 390, 'height': 844}, tab='today'); await pg.wait_for_timeout(400)
