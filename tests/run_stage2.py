import asyncio, pathlib, json
from playwright.async_api import async_playwright
HERE = pathlib.Path(__file__).parent
OUT = HERE / "shots2"; OUT.mkdir(exist_ok=True)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        errs = []
        async def page(w, h, role='manager', hash=''):
            pg = await b.new_page(viewport={"width": w, "height": h})
            pg.on("pageerror", lambda e: errs.append(str(e)))
            pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
            await pg.add_init_script(f"window.__role='{role}'")
            await pg.goto((HERE / "staff-test.html").as_uri() + hash)
            await pg.wait_for_timeout(400)
            return pg
        # kitchen role on a tablet
        pg = await page(1180, 820, 'kitchen')
        print('kitchen tabs', await pg.eval_on_selector_all('.ccs-nav-item', 'els=>els.map(e=>e.dataset.tab)'))
        await pg.screenshot(path=str(OUT / "k1-board-tablet.png"), full_page=True)
        await pg.click('[data-act="open-kitchen"][data-id="o3"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT / "k2-qc.png"))
        await pg.click('[data-act="k-ready"]'); await pg.wait_for_timeout(200)
        print('qc error shown:', await pg.eval_on_selector('#ccs-sheet', 'e=>e.innerText.includes("Enter the name of the person")'))
        await pg.fill('#k-qc', 'Baker One'); await pg.click('[data-act="k-ready"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="close"]'); await pg.wait_for_timeout(250)
        await pg.click('[data-act="open-kitchen"][data-id="o1"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT / "k3-late.png"))
        await pg.close()
        # kitchen on a phone
        pg = await page(390, 844, 'kitchen')
        await pg.screenshot(path=str(OUT / "k4-phone.png"), full_page=True)
        sw = await pg.evaluate('document.documentElement.scrollWidth'); print('phone scrollWidth', sw)
        await pg.close()
        # manager: order with delivery, ready-gating, print
        pg = await page(1280, 860)
        await pg.click('[data-tab="orders"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="filter"][data-v="today"]'); await pg.wait_for_timeout(150)
        await pg.screenshot(path=str(OUT / "m1-orders-today.png"), full_page=True)
        await pg.click('[data-act="open-order"][data-id="o3"]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT / "m2-delivery-order.png"))
        await pg.click('[data-act="panel"][data-v="fulfil"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="f-zone"][data-v="Other area"]'); await pg.wait_for_timeout(100)
        await pg.screenshot(path=str(OUT / "m3-fulfil.png"))
        await pg.fill('#f-fee', '20'); await pg.click('[data-act="do-fulfil"]'); await pg.wait_for_timeout(300)
        calls = await pg.evaluate('window.__calls.filter(c=>c[1]==="staff_set_fulfilment")')
        print('fulfil call', json.dumps(calls[-1][2]) if calls else None)
        await pg.click('[data-act="close"]'); await pg.wait_for_timeout(250)
        await pg.click('[data-act="open-order"][data-id="o4"]'); await pg.wait_for_timeout(400)
        await pg.click('[data-act="panel"][data-v="collected"]'); await pg.wait_for_timeout(150)
        await pg.screenshot(path=str(OUT / "m4-collect.png"))
        await pg.fill('#ccs-note', 'Test Customer B'); await pg.click('[data-act="do-collected"]'); await pg.wait_for_timeout(200)
        c = await pg.evaluate('window.__calls.filter(c=>c[1]==="staff_order_action").pop()'); print('collected call', json.dumps(c[2]))
        await pg.click('[data-act="panel"][data-v="brief"]'); await pg.wait_for_timeout(150)
        await pg.evaluate('window.print = function(){ window.__printed = (window.__printed||0)+1; }')
        await pg.click('[data-act="do-brief"][data-v="A4"]'); await pg.wait_for_timeout(600)
        await pg.evaluate("(function(){var e=document.querySelector('#ccs-sheet [data-act=brief-print]'); if(e) e.click()})()"); await pg.wait_for_timeout(700)
        print('printed', await pg.evaluate('window.__printed'), 'class', await pg.evaluate('document.body.className'))
        await pg.emulate_media(media="print")
        await pg.pdf(path=str(OUT / "brief-A4.pdf"), format="A4", prefer_css_page_size=True)
        await pg.set_viewport_size({"width": 794, "height": 1123})
        await pg.screenshot(path=str(OUT / "brief-A4.png"), full_page=True)
        await pg.emulate_media(media="screen")
        await pg.evaluate('document.body.classList.remove("ccs-printing")')
        await pg.set_viewport_size({"width": 1280, "height": 860})
        await pg.click('[data-act="panel"][data-v="brief"]'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="do-brief"][data-v="A5"]'); await pg.wait_for_timeout(600)
        await pg.evaluate("(function(){var e=document.querySelector('#ccs-sheet [data-act=brief-print]'); if(e) e.click()})()"); await pg.wait_for_timeout(700)
        await pg.emulate_media(media="print")
        await pg.pdf(path=str(OUT / "brief-A5.pdf"), prefer_css_page_size=True)
        await pg.set_viewport_size({"width": 560, "height": 794})
        await pg.screenshot(path=str(OUT / "brief-A5.png"), full_page=True)
        await pg.emulate_media(media="screen")
        await pg.close()
        # walk-in with delivery
        pg = await page(1024, 820, 'manager', '#new')
        await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500)
        await pg.click('[data-act="n-pick"]'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="n-prod"][data-v="red-velvet"]'); await pg.click('[data-act="n-size"][data-v="8"]'); await pg.wait_for_timeout(100)
        await pg.click('[data-act="n-next"]'); await pg.click('[data-act="n-finish"][data-v="standard"]'); await pg.click('[data-act="n-diet"][data-v="no"]'); await pg.click('[data-act="n-finish-next"]'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="n-method"][data-v="delivery"]'); await pg.wait_for_timeout(100)
        await pg.click('[data-act="n-zone"][data-v="Nadi town"]'); await pg.wait_for_timeout(100)
        d = await pg.evaluate("(()=>{var d=new Date(new Intl.DateTimeFormat('en-CA',{timeZone:'Pacific/Fiji'}).format(new Date())+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+4);return d.toISOString().slice(0,10)})()")
        await pg.click('[data-act="n-date-other"]'); await pg.fill('#n-date', d); await pg.wait_for_timeout(150)
        await pg.click('[data-act="n-time"][data-v="11:00"]'); await pg.wait_for_timeout(150)
        print('address error shown:', await pg.evaluate('document.body.innerText.includes("Enter the delivery address")'))
        await pg.fill('#n-address', '12 Test Road, Nadi'); await pg.click('[data-act="n-time"][data-v="11:00"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=str(OUT / "w1-delivery-pay.png"), full_page=True)
        await pg.click('[data-act="n-submit"]'); await pg.wait_for_timeout(300)
        c = await pg.evaluate('window.__calls.filter(c=>c[1]==="staff_create_order").pop()'); print('create delivery', json.dumps(c[2]['p']['delivery']))
        await pg.close()
        # settings
        pg = await page(1024, 900)
        await pg.evaluate("document.querySelector('.ccs-nav [data-tab=settings]').click()"); await pg.wait_for_timeout(300)
        await pg.evaluate('document.querySelectorAll("details").forEach(d=>{ if(d.innerText.startsWith("Delivery")) d.open=true })')
        await pg.screenshot(path=str(OUT / "s1-settings.png"), full_page=True)
        await pg.fill('#dz-f-z3', '25'); await pg.click('[data-act="save-zones"]'); await pg.wait_for_timeout(200)
        print('zone update', json.dumps(await pg.evaluate('window.__calls.filter(c=>c[1]==="delivery_zones")')))
        await pg.close()
        print('ERRORS:', errs)
        await b.close()
asyncio.run(main())
