"""Phase A checks: each finding from the usability audit, tested on the local copy with invented data."""
import asyncio, pathlib, json
from playwright.async_api import async_playwright
HERE = pathlib.Path(__file__).parent
OUT = HERE / "shotsA"; OUT.mkdir(exist_ok=True)
TAB = dict(viewport={"width": 1180, "height": 820}, has_touch=True, is_mobile=True)
R = {}
def check(name, ok, detail=''):
    R[name] = bool(ok); print(('PASS ' if ok else 'FAIL ') + name + (' -> ' + str(detail) if detail != '' else ''))

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); errs = []
        async def page(role='manager', ctx=None, dev=TAB):
            ctx = ctx or await b.new_context(**dev)
            pg = await ctx.new_page()
            pg.on("pageerror", lambda e: errs.append(str(e)))
            await pg.add_init_script(f"window.__role='{role}'")
            await pg.goto((HERE / "staff-test.html").as_uri()); await pg.wait_for_timeout(450)
            return ctx, pg
        refresh = "document.dispatchEvent(new Event('visibilitychange'))"

        # U2 kitchen refresh keeps typed names
        ctx, pg = await page('kitchen')
        await pg.click('[data-act="open-kitchen"][data-id="o3"]'); await pg.wait_for_timeout(300)
        await pg.fill('#k-qc', 'Baker One'); await pg.fill('#k-who', 'New Baker'); await pg.focus('#k-qc')
        await pg.evaluate(refresh); await pg.wait_for_timeout(400)
        qc = await pg.eval_on_selector('#k-qc', 'e=>e.value'); who = await pg.eval_on_selector('#k-who', 'e=>e.value')
        check('U2 quality-check name kept through refresh', qc == 'Baker One', qc)
        check('U2 made-by name kept through refresh', who == 'New Baker', who)
        check('U2 cursor stays in the field', await pg.evaluate("document.activeElement.id") == 'k-qc')
        # U5 outside tap with typing keeps the sheet
        await pg.mouse.click(40, 500); await pg.wait_for_timeout(300)
        check('U5 kitchen card stays open after outside tap', await pg.evaluate("document.getElementById('ccs-sheet').classList.contains('ccs-open')"))
        await pg.click('[data-act="k-ready"]'); await pg.wait_for_timeout(300)
        call = await pg.evaluate("window.__calls.filter(c=>c[1]==='kitchen_set_stage').pop()")
        check('U2 the kept name is the one sent', call and call[2]['p_name'] == 'Baker One', call and call[2])
        await ctx.close()

        # U3 older order search, U22 focus kept, U13 Delivered label, U5 order sheet
        ctx, pg = await page()
        await pg.click('[data-tab="orders"]'); await pg.wait_for_timeout(200)
        await pg.click('#ccs-q'); await pg.keyboard.type('CC-0500'); await pg.wait_for_timeout(900)
        txt = await pg.inner_text('#ccs-main')
        check('U3 older order found by order number', 'older orders' in txt.lower() and 'CC-0500' in txt)
        check('U13 delivered order shows Delivered', 'Delivered' in txt and 'Collected' not in txt.lower().split('older orders')[-1].replace('collect from', ''))
        await pg.screenshot(path=str(OUT / 'u3-older-number.png'))
        await pg.fill('#ccs-q', ''); await pg.keyboard.type('Test Customer A'); await pg.wait_for_timeout(900)
        txt = await pg.inner_text('#ccs-main')
        check('U3 older order found by name', 'CC-0500' in txt and 'CC-1001' in txt and txt.count('CC-1001') == 1, txt.count('CC-1001'))
        await pg.evaluate(refresh); await pg.wait_for_timeout(400)
        check('U22 search keeps focus through refresh', await pg.evaluate("document.activeElement.id") == 'ccs-q')
        await pg.screenshot(path=str(OUT / 'u3-older-name.png'))
        await pg.click('[data-act="filter"][data-v="upcoming"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="open-order"][data-id="o4"]'); await pg.wait_for_timeout(400)
        await pg.click('[data-act="panel"][data-v="note"]'); await pg.fill('#ccs-note', 'Customer called about the message')
        await pg.mouse.click(30, 400); await pg.wait_for_timeout(300)
        check('U5 order stays open after outside tap with a typed note', await pg.evaluate("document.getElementById('ccs-sheet').classList.contains('ccs-open')"))
        check('U5 typed note still there', await pg.eval_on_selector('#ccs-note', 'e=>e.value') == 'Customer called about the message')
        await pg.screenshot(path=str(OUT / 'u5-kept.png'))
        # U10 saving state: slow down the server reply
        await pg.evaluate("() => { const real = window.__ccsMock.rpc; window.__ccsMock.rpc = function(f,a){ return new Promise(r => setTimeout(() => r(real(f,a)), 700)); }; }")
        await pg.click('[data-act="do-note"]'); await pg.wait_for_timeout(150)
        btn = await pg.evaluate("(()=>{const b=document.querySelector('[data-act=do-note]');return b?[b.textContent,b.disabled]:null})()")
        check('U10 button shows Saving and is locked', btn and 'Saving' in btn[0] and btn[1], btn)
        await pg.screenshot(path=str(OUT / 'u10-saving.png'))
        await pg.wait_for_timeout(1500)
        # outside tap with nothing typed still closes
        await pg.mouse.click(30, 400); await pg.wait_for_timeout(300)
        check('U5 outside tap still closes when nothing is typed', not await pg.evaluate("document.getElementById('ccs-sheet').classList.contains('ccs-open')"))
        await ctx.close()

        # U9 offline wording, banner, typed text kept; expired sign-in
        ctx, pg = await page()
        await pg.click('[data-tab="orders"]'); await pg.click('[data-act="filter"][data-v="upcoming"]'); await pg.click('[data-act="open-order"][data-id="o4"]'); await pg.wait_for_timeout(400)
        await pg.evaluate("() => { window.__ccsMock.rpc = function(){ return Promise.resolve({ error: { message: 'TypeError: Failed to fetch' } }); }; }")
        await pg.click('[data-act="panel"][data-v="note"]'); await pg.fill('#ccs-note', 'x'); await pg.click('[data-act="do-note"]'); await pg.wait_for_timeout(300)
        msg = await pg.eval_on_selector('#ccs-toast', 'e=>e.textContent')
        check('U9 plain offline message', msg.startswith('No internet connection. Nothing was saved.'), msg)
        check('U9 note kept after failure', await pg.eval_on_selector('#ccs-note', 'e=>e.value') == 'x')
        check('U10 button unlocked after failure', await pg.eval_on_selector('[data-act="do-note"]', 'e=>!e.disabled && e.textContent==="Save note"'))
        await ctx.set_offline(True); await pg.wait_for_timeout(300)
        check('U9 offline banner shows', await pg.evaluate("!!document.getElementById('ccs-offline')"))
        await pg.screenshot(path=str(OUT / 'u9-offline.png'))
        await ctx.set_offline(False); await pg.wait_for_timeout(300)
        check('U9 banner clears when back online', not await pg.evaluate("!!document.getElementById('ccs-offline')"))
        await pg.evaluate("() => { window.__ccsMock.rpc = function(){ return Promise.resolve({ error: { message: 'JWT expired', code: 'PGRST301' } }); }; }")
        await pg.click('[data-act="do-note"]'); await pg.wait_for_timeout(300)
        t = await pg.inner_text('#cc-staff')
        check('U9 expired sign-in returns to sign in with a plain message', 'Staff sign in' in t and 'sign-in has expired' in t)
        await ctx.close()

        # U6 draft kept through reload; Today reminder; U18 Start over asks; sign out clears
        ctx = await b.new_context(**TAB)
        ctx, pg = await page(ctx=ctx)
        await pg.click('[data-tab="new"]'); await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500)
        await pg.click('[data-act="n-pick"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="n-prod"][data-v="cheesecake"]'); await pg.click('[data-act="n-size"] >> nth=1'); await pg.wait_for_timeout(100)
        key1 = await pg.evaluate("JSON.parse(localStorage.getItem('ccs-draft-u1')).key")
        await pg.reload(); await pg.wait_for_timeout(500)
        t = await pg.inner_text('#ccs-main')
        check('U6 Today shows the unfinished order', 'Unfinished order for Test Customer A' in t)
        await pg.screenshot(path=str(OUT / 'u6-today.png'))
        await pg.click('.ccs-draftbar [data-tab="new"]'); await pg.wait_for_timeout(300)
        t = await pg.inner_text('#ccs-main')
        check('U6 order carries on with customer and cake', 'Test Customer A' in t and 'Carrying on the unfinished order' in t and await pg.evaluate("document.querySelector('[data-act=n-size][aria-pressed=true]') !== null"))
        check('U6 same duplicate-protection key after reload', await pg.evaluate("JSON.parse(localStorage.getItem('ccs-draft-u1')).key") == key1)
        await pg.screenshot(path=str(OUT / 'u6-restored.png'))
        await pg.click('[data-act="new-again"]'); await pg.wait_for_timeout(200)
        t = await pg.inner_text('#ccs-main')
        check('U18 Start over asks first', 'Clear this order?' in t and 'Test Customer A' in t)
        await pg.screenshot(path=str(OUT / 'u18-confirm.png'))
        await pg.click('[data-act="new-keep"]'); await pg.wait_for_timeout(200)
        check('U18 Keep going keeps the order', 'Test Customer A' in await pg.inner_text('#ccs-main'))
        await pg.click('[data-act="new-again"]'); await pg.click('[data-act="new-clear"]'); await pg.wait_for_timeout(200)
        check('U18 Clear order empties it and the stored copy', await pg.evaluate("!document.querySelector('.ccs-sum') && localStorage.getItem('ccs-draft-u1') === null"))
        # draft then sign out clears storage
        await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500); await pg.click('[data-act="n-pick"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="signout"]'); await pg.wait_for_timeout(300); await pg.click('[data-act="signout"][data-sure="1"]'); await pg.wait_for_timeout(300)
        check('U6 sign out clears the stored order', await pg.evaluate("localStorage.getItem('ccs-draft-u1') === null"))
        await ctx.close()
        # full walk-in still saves and clears the draft
        ctx, pg = await page()
        await pg.click('[data-tab="new"]'); await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500); await pg.click('[data-act="n-pick"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="n-prod"][data-v="cheesecake"]'); await pg.click('[data-act="n-size"] >> nth=0'); await pg.click('[data-act="n-next"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="n-finish"][data-v="standard"]'); await pg.click('[data-act="n-diet"][data-v="no"]'); await pg.click('[data-act="n-finish-next"]'); await pg.wait_for_timeout(200)
        d = await pg.evaluate("(()=>{const d=new Date();d.setDate(d.getDate()+5);return d.toISOString().slice(0,10)})()")
        await pg.click('[data-act="n-date-other"]'); await pg.fill('#n-date', d); await pg.wait_for_timeout(200); await pg.click('[data-act="n-time"] >> nth=3'); await pg.wait_for_timeout(200)
        await pg.click('[data-act="n-submit"]'); await pg.wait_for_timeout(400)
        t = await pg.inner_text('#ccs-main')
        check('Walk-in order still saves', 'CC-1009 is saved' in t, t[:60])
        check('U6 saved order removes the stored copy', await pg.evaluate("localStorage.getItem('ccs-draft-u1') === null"))
        await ctx.close()

        # U24 closed day needs a second tap
        ctx, pg = await page()
        await pg.evaluate("() => { const real = window.__ccsMock.from; window.__ccsMock.from = function(t){ const q = real(t); if (t === 'closed_dates') { const th = q.then; q.then = function(ok, bad){ return Promise.resolve({ data: [{ id: 'cd1', closed_on: '2026-12-25', reason: 'Christmas' }] }).then(ok, bad); }; } return q; }; }")
        await pg.evaluate("document.querySelector('.ccs-nav [data-tab=settings]').click()"); await pg.wait_for_timeout(400)
        await pg.click('summary:has-text("Closed days")'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="del-closed"]'); await pg.wait_for_timeout(150)
        first = await pg.evaluate("window.__calls.filter(c=>c[0]==='delete').length")
        label = await pg.eval_on_selector('[data-act="del-closed"]', 'e=>e.textContent')
        check('U24 first tap only asks', first == 0 and label == 'Tap again to remove', label)
        await pg.click('[data-act="del-closed"]'); await pg.wait_for_timeout(200)
        check('U24 second tap removes', await pg.evaluate("window.__calls.filter(c=>c[0]==='delete').length") == 1)
        await ctx.close()

        # Phone layout: no sideways scroll on changed screens
        PH = dict(viewport={"width": 360, "height": 740}, has_touch=True, is_mobile=True)
        ctx, pg = await page(dev=PH)
        await pg.click('[data-tab="new"]'); await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500); await pg.click('[data-act="n-pick"]')
        await pg.click('[data-tab="today"]'); await pg.wait_for_timeout(300)
        ok1 = await pg.evaluate("document.documentElement.scrollWidth <= innerWidth")
        await pg.screenshot(path=str(OUT / 'phone-today-draft.png'))
        await pg.click('[data-tab="orders"]'); await pg.click('#ccs-q'); await pg.keyboard.type('CC-0500'); await pg.wait_for_timeout(900)
        ok2 = await pg.evaluate("document.documentElement.scrollWidth <= innerWidth")
        check('Small phone: no sideways scroll', ok1 and ok2)
        await ctx.close()
        await b.close()
        check('No script errors', not errs, errs)
    print('FAILED:', [k for k, v in R.items() if not v])
asyncio.run(main())
