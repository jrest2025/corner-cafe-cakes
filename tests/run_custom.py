"""Custom cake not on the menu: New order, Custom cake, details, save with or without a price; add the price; email it;
confirm with how the customer agreed; the kitchen slip goes out on confirm. Invented data only."""
import asyncio, pathlib, sys
from playwright.async_api import async_playwright
HERE = pathlib.Path(__file__).parent; OUT = HERE / "shotsCustom"; OUT.mkdir(exist_ok=True)
PAGE = sys.argv[1] if len(sys.argv) > 1 else "hosted-staff.html"
R = []
def check(n, ok, d=''):
    R.append(bool(ok)); print(('PASS ' if ok else 'FAIL ') + n + (' -> ' + str(d)[:300] if not ok and d != '' else ''))
async def start(b, vp, role='front_of_house', init=''):
    ctx = await b.new_context(viewport=vp, is_mobile=vp['width'] < 760, has_touch=vp['width'] < 760); pg = await ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.add_init_script(f"window.__role='{role}'; window.__reqOrders=true; window.__setupGuest=true; window.__printed=0; window.print=function(){{window.__printed++}}; try{{localStorage.clear()}}catch(e){{}} {init}")
    await pg.goto((HERE / PAGE).as_uri()); await pg.wait_for_timeout(900)
    return ctx, pg, errs
async def js(pg, sel, wait=250):
    r = await pg.evaluate(f"(function(){{var e=document.querySelector({sel!r}); if(e) e.click(); return !!e}})()"); await pg.wait_for_timeout(wait); return r
async def nxt(pg): await js(pg, '.sl-stepbar [data-act="sl-next"]')
async def new_btn(pg): await pg.evaluate("[].slice.call(document.querySelectorAll('[data-tab=new]')).filter(function(e){return e.offsetParent}).pop().click()"); await pg.wait_for_timeout(500)
async def open_order(pg, ref):
    await pg.click('.ccs-nav [data-tab="orders"]'); await pg.wait_for_timeout(250)
    if await pg.locator('#ccs-q').count(): await pg.fill('#ccs-q', ref)
    await pg.wait_for_timeout(300)
    await pg.evaluate(f"(function(){{var b=[].slice.call(document.querySelectorAll('[data-act=open-order]')).filter(function(x){{return x.textContent.indexOf({ref!r})>-1}})[0]; if(b) b.click();}})()")
    await pg.wait_for_timeout(500)
async def creates(pg): return await pg.evaluate("window.__calls.filter(function(c){return c[1]==='staff_create_order'}).map(function(c){return c[2].p})")
async def take(pg, w, price=None):
    await js(pg, '[data-act="n-source"][data-v="phone"]')
    await js(pg, '[data-act="n-req"]')
    body = await pg.inner_text('body')
    check(f'{w}: custom cake shows its own fields', 'What should it look like?' in body and 'Size or servings' in body and 'Price (FJD)' in body, body[:200])
    check(f'{w}: no finish choice for a custom cake', not await pg.evaluate("!!document.querySelector('[data-act=n-finish]')"))
    await nxt(pg)
    t = await pg.inner_text('body')
    check(f'{w}: cannot go on without the design', 'Describe how the cake should look' in t)
    await pg.fill('#n-design', 'Two tier, white and gold, fresh flowers')
    await nxt(pg)
    t = await pg.inner_text('body')
    check(f'{w}: cannot go on without the size', 'Write the size or how many people it serves' in t)
    await pg.fill('#n-sizenote', 'About 30 people, two tiers')
    flav = await pg.evaluate("(function(){var e=document.querySelector('[data-act=n-reqflav]'); e.click(); return e.dataset.v})()"); await pg.wait_for_timeout(250)
    if price: await pg.fill('#n-reqprice', str(price)); await pg.wait_for_timeout(700)
    live = await pg.evaluate("(document.querySelector('.sl-live')||document.body).innerText")
    check(f'{w}: slip preview shows the custom cake and size', ('Custom cake, ' + flav) in live and 'About 30 people, two tiers' in live, live[:300])
    live = await pg.evaluate("(document.querySelector('.sl-live')||document.body).innerText")
    check(f'{w}: slip preview price', ('To be priced' in live) if not price else ('$' + str(price)) in live, live[-300:])
    await pg.screenshot(path=str(OUT / f'new-{w}{"-price" if price else ""}.png'))
    await nxt(pg)
    await pg.fill('#n-name', 'Test Guest'); await nxt(pg)
    await pg.fill('#n-phone', '912 3456'); await pg.wait_for_timeout(450)
    await js(pg, '[data-act="sl-opt"][data-v="no"]'); await nxt(pg)
    t = await pg.inner_text('body')
    await js(pg, '.ccs-datechips [data-act="n-date"]:not(.ccs-chip-soon):not([disabled])')
    if isinstance(w, int) and w < 760: await nxt(pg)
    await js(pg, '[data-act="n-time"][data-v="15:00"]'); await nxt(pg)
    await js(pg, '.sl-stepbar [data-act="sl-skip"]')
    await js(pg, '[data-act="n-diet"][data-v="no"]'); await nxt(pg)
    await js(pg, '.sl-stepbar [data-act="sl-skip"]')
    t = await pg.inner_text('body')
    check(f'{w}: read-over says when it goes to the kitchen', 'The kitchen gets it only after Confirm order.' in t, t[-500:])
    btn = await pg.evaluate("(document.querySelector('[data-act=n-submit]')||{}).textContent||''")
    check(f'{w}: save button says Save custom cake', btn.startswith('Save custom cake'), btn)
    await js(pg, '[data-act="n-submit"]', 1000)
    return flav
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        for vp in ({'width': 1280, 'height': 900}, {'width': 390, 'height': 844}):
            w = vp['width']
            ctx, pg, errs = await start(b, vp)
            await new_btn(pg); flav = await take(pg, w)
            c = await creates(pg)
            check(f'{w}: saved as a custom cake without a price', c and c[-1].get('product_code') == 'custom-cake' and c[-1].get('size_note') == 'About 30 people, two tiers' and c[-1].get('variant') == flav and c[-1].get('price') is None and c[-1].get('size_inch') is None, c[-1] if c else None)
            check(f'{w}: no page errors', not errs, errs)
            await ctx.close()
        ctx, pg, errs = await start(b, {'width': 1280, 'height': 900})
        await new_btn(pg); await take(pg, 'price', price=150)
        c = await creates(pg)
        check('with a price: price sent', c and c[-1].get('price') == 150, c[-1] if c else None)
        await ctx.close()

        # Needs a price -> Add the price
        ctx, pg, errs = await start(b, {'width': 1280, 'height': 900})
        await open_order(pg, 'CC-1021')
        t = await pg.inner_text('#ccs-sheet')
        check('unpriced: order shows To price and Add the price', 'To price' in t and 'Add the price' in t, t[:500])
        check('unpriced: no Confirm order yet', not await pg.evaluate("[].slice.call(document.querySelectorAll('#ccs-sheet button')).some(function(b){return b.textContent==='Confirm order'})"))
        await js(pg, '#ccs-sheet [data-act="panel"][data-v="quote"]')
        check('add price: flavour and size can be set', await pg.evaluate("!!document.getElementById('q-flav') && !!document.getElementById('q-size')"))
        await pg.fill('#q-price', '120'); await pg.fill('#q-flav', 'Chocolate')
        await js(pg, '#ccs-sheet [data-act="do-quote"]', 800)
        q = await pg.evaluate("window.__quoteSet")
        check('add price: saved with flavour and size', q and q.get('p_price') == 120 and q.get('p_flavour') == 'Chocolate' and q.get('p_size_note') == '8 inch', q)
        t = await pg.inner_text('#ccs-sheet')
        check('add price: now Waiting for customer with Confirm order', 'Waiting for customer' in t and 'Confirm order' in t, t[:400])
        await pg.screenshot(path=str(OUT / 'priced.png'))
        await ctx.close()

        # Waiting for customer -> email the price -> confirm with method -> kitchen slip
        ctx, pg, errs = await start(b, {'width': 1280, 'height': 900})
        await open_order(pg, 'CC-1020')
        t = await pg.inner_text('#ccs-sheet')
        check('order shows the custom cake line', 'Custom cake, Lemon, About 30 people, two tiers' in t, t[:600])
        await js(pg, '#ccs-sheet [data-act="send-quote"]', 600)
        check('email the price: sent once', await pg.evaluate("window.__quoteSent") == 1)
        await js(pg, '#ccs-sheet [data-act="panel"][data-v="confirm"]')
        await pg.screenshot(path=str(OUT / 'confirm.png'))
        await js(pg, '#ccs-sheet [data-act="do-confirm"]', 400)
        t = await pg.inner_text('#ccs-sheet')
        check('confirm: needs how the customer agreed', 'Choose how the customer agreed.' in t)
        await js(pg, '#ccs-sheet [data-act="cfm-how"][data-v="verbal"]')
        await js(pg, '#ccs-sheet [data-act="do-confirm"]', 1800)
        a = await pg.evaluate("window.__confirmArgs")
        check('confirm: price and method recorded', a and a.get('p_final_total') == 150 and a.get('p_note') == 'Customer confirmed verbally', a)
        briefs = await pg.evaluate("window.__briefCalls || 0")
        check('confirm: kitchen slip sent straight away', briefs == 1, briefs)
        t = await pg.inner_text('#ccs-sheet')
        check('confirm: the slip panel shows it was emailed', 'Kitchen slip' in t and 'Emailed to' in t, t[:500])
        check('flow: no page errors', not errs, errs)
        await ctx.close()

        # Deposit: confirm waits for the deposit, no kitchen slip yet
        ctx, pg, errs = await start(b, {'width': 1280, 'height': 900})
        await open_order(pg, 'CC-1020')
        await js(pg, '#ccs-sheet [data-act="panel"][data-v="confirm"]')
        await js(pg, '#ccs-sheet [data-act="cfm-how"][data-v="email"]')
        await pg.fill('#ccs-dep', '50')
        await js(pg, '#ccs-sheet [data-act="do-confirm"]', 1500)
        a = await pg.evaluate("window.__confirmArgs")
        check('deposit: method is email and deposit sent', a and a.get('p_note') == 'Customer accepted by email' and a.get('p_deposit') == 50, a)
        check('deposit: no kitchen slip until paid', (await pg.evaluate("window.__briefCalls || 0")) == 0)
        await ctx.close()

        # Phone fit for the confirm panel
        ctx, pg, errs = await start(b, {'width': 375, 'height': 740})
        await open_order(pg, 'CC-1020')
        await js(pg, '#ccs-sheet [data-act="panel"][data-v="confirm"]')
        fit = await pg.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1 && [].slice.call(document.querySelectorAll('#ccs-sheet .ccs-panel button')).every(function(x){var r=x.getBoundingClientRect(); return r.right<=window.innerWidth+1})")
        check('phone: confirm panel fits', fit)
        await pg.screenshot(path=str(OUT / 'confirm-phone.png'))
        await ctx.close()
        await b.close()
    print(f"{sum(R)}/{len(R)} passed")
asyncio.run(main())
