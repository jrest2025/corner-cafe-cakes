import asyncio, sys, pathlib
from playwright.async_api import async_playwright

HERE = pathlib.Path(__file__).parent
OUT = HERE / "shots"; OUT.mkdir(exist_ok=True)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={"width": 1024, "height": 768})
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
        await pg.goto((HERE / "staff-test.html").as_uri())
        await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT / "0-today.png"), full_page=True)
        await pg.click('[data-act="goto"][data-v="action"]'); await pg.wait_for_timeout(200)
        print("goto ->", await pg.eval_on_selector('[aria-current="page"]', 'e=>e.dataset.tab'))
        await pg.screenshot(path=str(OUT / "1-orders.png"))
        await pg.click('[data-act="filter"][data-v="upcoming"]'); await pg.wait_for_timeout(150)
        await pg.screenshot(path=str(OUT / "2-upcoming.png"))
        await pg.click('[data-act="open-order"][data-id="o1"]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=str(OUT / "3-detail.png"))
        await pg.click('[data-act="panel"][data-v="confirm"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=str(OUT / "4-confirm.png"))
        await pg.click('[data-act="close"]'); await pg.wait_for_timeout(300)
        # new order flow
        await pg.click('[data-tab="new"]'); await pg.wait_for_timeout(150)
        await pg.fill('#n-phone', '912 0001'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=str(OUT / "5-new-search.png"))
        await pg.click('[data-act="n-pick"]'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="n-prod"][data-v="chocolate-mudcake-mocha"]')
        await pg.click('[data-act="n-var"][data-v="Mocha"]')
        await pg.click('[data-act="n-size"][data-v="8"]'); await pg.wait_for_timeout(100)
        await pg.screenshot(path=str(OUT / "6-new-cake.png"))
        await pg.click('[data-act="n-next"]')
        await pg.click('[data-act="n-finish"][data-v="standard"]')
        await pg.click('[data-act="n-diet"][data-v="no"]')
        await pg.click('[data-act="n-finish-next"]'); await pg.wait_for_timeout(100)
        # tomorrow is short notice
        import datetime
        d = (datetime.datetime.utcnow() + datetime.timedelta(hours=12, days=1)).strftime("%Y-%m-%d")
        await pg.click('[data-act="n-date-other"]'); await pg.fill('#n-date', d); await pg.wait_for_timeout(150)
        await pg.screenshot(path=str(OUT / "7-new-when.png"))
        await pg.fill('#n-rush', 'Kitchen agreed, from today batch')
        await pg.fill('#n-rushby', 'Chef Test')
        await pg.click('[data-act="n-time"][data-v="15:00"]'); await pg.wait_for_timeout(150)
        await pg.click('[data-act="n-askdep"]'); await pg.click('[data-act="n-dep"][data-v="half"]')
        await pg.click('[data-act="n-paynow"]'); await pg.wait_for_timeout(100)
        await pg.screenshot(path=str(OUT / "8-new-pay.png"), full_page=True)
        await pg.click('[data-act="n-submit"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT / "9-new-done.png"))
        sub = await pg.evaluate("JSON.stringify(window.__calls.filter(c=>c[1]==='staff_create_order').map(c=>c[2]))")
        print("CREATE PAYLOAD:", sub)
        await pg.evaluate("document.querySelector('.ccs-nav [data-tab=customers]').click()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT / "10-customers.png"))
        await pg.click('tr[data-id="c1"]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT / "11-customer.png"))
        await pg.click('[data-act="close"]'); await pg.wait_for_timeout(300)
        await pg.evaluate("document.querySelector('.ccs-nav [data-tab=settings]').click()"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT / "12-settings.png"), full_page=True)
        # phone width
        await pg.set_viewport_size({"width": 390, "height": 800})
        await pg.click('[data-tab="today"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT / "13-phone.png"), full_page=True)
        sw = await pg.evaluate("document.documentElement.scrollWidth")
        print("phone scrollWidth", sw)
        # kitchen view
        pg2 = await b.new_page(viewport={"width": 1024, "height": 768})
        pg2.on("pageerror", lambda e: errs.append("kitchen: " + str(e)))
        await pg2.add_init_script("window.__role='kitchen'")
        await pg2.goto((HERE / "staff-test.html").as_uri()); await pg2.wait_for_timeout(400)
        await pg2.screenshot(path=str(OUT / "14a-kitchen-today.png"))
        await pg2.click('[data-act="open-kitchen"][data-id="o1"]'); await pg2.wait_for_timeout(400)
        await pg2.screenshot(path=str(OUT / "14-kitchen.png"))
        print("ERRORS:", errs)
        await b.close()

asyncio.run(main())
