"""Order Slip, filled in one stage at a time. Invented data only."""
import asyncio, pathlib, sys
from playwright.async_api import async_playwright
HERE = pathlib.Path(__file__).parent; OUT = HERE / "shotsB"; OUT.mkdir(exist_ok=True)
PAGE = sys.argv[1] if len(sys.argv) > 1 else "hosted-staff.html"
R = []
def check(n, ok, d=''):
    R.append(bool(ok)); print(('PASS ' if ok else 'FAIL ') + n + (' -> ' + str(d)[:300] if not ok and d != '' else ''))
TAB = {'width': 1024, 'height': 768}; PHONE = {'width': 390, 'height': 844}
async def newpage(b, vp=TAB, role='manager', init=''):
    ctx = await b.new_context(viewport=vp, is_mobile=vp['width'] < 760, has_touch=vp['width'] < 760); pg = await ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.add_init_script(f"window.__role='{role}'; window.print=function(){{}}; {init}")
    await pg.goto((HERE / PAGE).as_uri()); await pg.wait_for_timeout(600)
    await pg.evaluate("(function(){try{localStorage.clear()}catch(e){}; var e=[].slice.call(document.querySelectorAll('[data-tab=new]')).pop(); e&&e.click()})()"); await pg.wait_for_timeout(400)
    return ctx, pg, errs
async def js(pg, sel):
    await pg.evaluate(f"(function(){{var e=document.querySelector({sel!r}); if(e) e.click(); return !!e}})()"); await pg.wait_for_timeout(220)
async def stage(pg): return await pg.inner_text('.sl-progress')
async def nxt(pg): await js(pg, '[data-act="sl-next"]'); await pg.wait_for_timeout(150)
async def creates(pg): return await pg.evaluate("window.__calls.filter(function(c){return c[1]==='staff_create_order'}).map(function(c){return c[2].p})")
async def open_lines(pg): return await pg.evaluate("document.querySelectorAll('#ccs-slipform .sl-line2.is-open').length + (document.querySelector('.sl-cakepick.is-open')?1:0)")
async def through(pg, name='Slip Test Guest', phone='912 0099', opt='yes'):
    await js(pg, '[data-act="n-cell"][data-v="cheesecake|8"]'); await nxt(pg)
    await pg.fill('#n-name', name); await nxt(pg)
    await pg.fill('#n-phone', phone); await pg.wait_for_timeout(450); await js(pg, f'[data-act="sl-opt"][data-v="{opt}"]'); await nxt(pg)
    await js(pg, '#sl-st-3 .ccs-datechips [data-act="n-date"]:not(.ccs-chip-soon)'); await js(pg, '#sl-st-3 [data-act="n-time"][data-v="15:00"]'); await nxt(pg)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx, pg, errs = await newpage(b)
        check('starts at step 1, the cake', 'Step 1 of 8' in await stage(pg) and 'Cake and size' in await stage(pg))
        check('only one line open at a time', await open_lines(pg) == 1)
        labels = await pg.evaluate("[].slice.call(document.querySelectorAll('#ccs-slipform .sl-line2 .sl-k')).map(function(e){return e.textContent.trim()})")
        check('the slip keeps the paper order', labels[:3] == ['Guest Name', 'Contact', 'Pickup Date'] and labels[3:6] == ['Type of cake', 'Size', 'Price'] and labels[-2:] == ['Order Taken by', 'Date'], labels)
        w = await pg.evaluate("document.querySelector('.sl-wrap').getBoundingClientRect().width")
        check('slip is paper width (600 px or less) on a tablet', w <= 600, w)
        fs = await pg.evaluate("parseFloat(getComputedStyle(document.querySelector('.sl-line2 .sl-k')).fontSize)")
        check('labels are at least 17 px', fs >= 17, fs)
        await nxt(pg)
        check('Next without a cake says what is needed and stays', 'Tap a price' in await pg.inner_text('.sl-cakepick') and 'Step 1 of 8' in await stage(pg))
        await js(pg, '[data-act="n-cell"][data-v="chocolate-mudcake-mocha|6"]'); await nxt(pg)
        check('a cake with flavours asks for the flavour first', 'Choose the flavour' in await pg.inner_text('.sl-cakepick') and 'Step 1' in await stage(pg))
        await js(pg, '[data-act="n-var"][data-v="Mocha"]'); await nxt(pg)
        check('then moves to step 2, guest name', 'Step 2 of 8' in await stage(pg) and await pg.evaluate("document.activeElement.id") == 'n-name')
        s = await pg.inner_text('#ccs-slipform')
        check('cake lines are written in from the table', 'Mocha' in s and '6 inch' in s and '$42' in s)
        await nxt(pg)
        check('guest name is required', 'Write the guest name' in await pg.inner_text('#sl-st-1'))
        await pg.fill('#n-name', 'Slip Test Guest'); await nxt(pg)
        check('step 3 contact opens; name shows as written with Change', 'Step 3 of 8' in await stage(pg) and 'Slip Test Guest' in await pg.inner_text('#sl-st-1') and await pg.locator('#sl-st-1 [data-act="sl-goto"]').count() == 1)
        await pg.fill('#n-phone', '912 0099'); await pg.wait_for_timeout(450); await nxt(pg)
        check('permission must be answered for a new guest', 'cake offers and reminders' in await pg.inner_text('#sl-st-2') and 'Step 3' in await stage(pg))
        await js(pg, '[data-act="sl-opt"][data-v="yes"]'); await nxt(pg)
        check('step 4 pickup opens', 'Step 4 of 8' in await stage(pg) and 'Agreed to cake offers' in await pg.inner_text('#sl-st-2'))
        await js(pg, '#sl-st-3 .ccs-chip-soon ~ .ccs-chip-soon')
        await js(pg, '#sl-st-3 [data-act="n-time"]:not([disabled])'); await nxt(pg)
        check('short notice needs a reason and approver before moving on', 'short-notice reason' in await pg.inner_text('#sl-st-3') and 'Step 4' in await stage(pg))
        await pg.fill('#n-rush', 'Spare base in the kitchen'); await pg.fill('#n-rushby', 'Test Manager'); await js(pg, '#sl-st-3 [data-act="n-time"]:not([disabled])'); await nxt(pg)
        check('step 5 candles and inscription', 'Step 5 of 8' in await stage(pg) and 'Short notice, approved by Test Manager' in await pg.inner_text('#sl-st-3'))
        await js(pg, '[data-act="sl-skip"]')
        check('optional step can be skipped to step 6 dietary', 'Step 6 of 8' in await stage(pg))
        await nxt(pg)
        check('dietary must be answered', 'dietary' in (await pg.inner_text('#sl-st-5')).lower() and 'Step 6' in await stage(pg))
        await js(pg, '[data-act="n-diet"][data-v="yes"]'); await js(pg, '[data-act="n-diets"][data-v="Other"]'); await nxt(pg)
        check('Other needs written details', 'Step 6' in await stage(pg))
        await pg.fill('#n-dnote', 'No sesame'); await nxt(pg)
        check('step 7 remarks', 'Step 7 of 8' in await stage(pg))
        await js(pg, '[data-act="n-occ"][data-v="Birthday"]'); await nxt(pg)
        check('step 8 read over shows Create order', 'Step 8 of 8' in await stage(pg) and await pg.locator('[data-act="n-submit"]').count() == 1)
        await pg.screenshot(path=str(OUT / 'tablet-readover.png'), full_page=True)
        await js(pg, '#sl-st-1 [data-act="sl-goto"]')
        check('Change reopens only that line', 'Step 2 of 8' in await stage(pg) and await open_lines(pg) == 1)
        await pg.fill('#n-name', 'Slip Test Guest Two'); await nxt(pg)
        check('after the change it returns to read over', 'Step 8 of 8' in await stage(pg) and 'Slip Test Guest Two' in await pg.inner_text('#sl-st-1'))
        await pg.evaluate("var b=document.querySelector('[data-act=\"n-submit\"]'); b.click(); b.click();"); await pg.wait_for_timeout(600)
        c = await creates(pg); x = c[0] if c else {}
        check('one order sent even when tapped twice', len(c) >= 1 and len(set(y['idempotency_key'] for y in c)) == 1)
        check('order has cake, flavour, guest, permission yes, dietary and occasion', x.get('product_code') == 'chocolate-mudcake-mocha' and x.get('variant') == 'Mocha' and (x.get('customer') or {}).get('name') == 'Slip Test Guest Two' and (x.get('customer') or {}).get('opt_in') is True and x.get('has_dietary') == 'yes' and x.get('occasion') == 'Birthday', x)
        check('saved screen shows the order number', 'CC-1009' in await pg.inner_text('#ccs-main'))
        check('no page errors', not errs, errs)
        await ctx.close()

        # Permission no is recorded as no
        ctx, pg, errs = await newpage(b)
        await through(pg, opt='no'); await js(pg, '[data-act="sl-skip"]'); await js(pg, '[data-act="n-diet"][data-v="no"]'); await nxt(pg); await js(pg, '[data-act="sl-skip"]')
        await js(pg, '[data-act="n-submit"]'); await pg.wait_for_timeout(500)
        c = await creates(pg)
        check('a No is sent as no permission', c and (c[0].get('customer') or {}).get('opt_in') is False, c and c[0].get('customer'))
        await ctx.close()

        # Existing guest found by name
        ctx, pg, errs = await newpage(b)
        await js(pg, '[data-act="n-cell"][data-v="cheesecake|8"]'); await nxt(pg)
        await pg.fill('#n-name', 'Customer A'); await pg.wait_for_timeout(700)
        check('typing a name finds an existing guest', await pg.locator('#sl-st-1 [data-act="n-pick"]').count() >= 1)
        await js(pg, '#sl-st-1 [data-act="n-pick"]'); await pg.wait_for_timeout(400)
        s = await pg.inner_text('#ccs-slipform')
        check('picking fills name and contact and asks for permission (needs confirming)', 'Test Customer A' in s and '912 0001' in s and 'Step 3 of 8' in await stage(pg) and 'needs confirming' in await pg.inner_text('#sl-st-2'))
        await ctx.close()

        # Failed save keeps everything
        ctx, pg, errs = await newpage(b, init="window.__createFail = true;")
        await through(pg); await js(pg, '[data-act="sl-skip"]'); await js(pg, '[data-act="n-diet"][data-v="no"]'); await nxt(pg); await js(pg, '[data-act="sl-skip"]')
        await js(pg, '[data-act="n-submit"]'); await pg.wait_for_timeout(600)
        t = await pg.inner_text('#sl-st-7')
        check('failed save says nothing was saved and all is kept', 'Not saved' in t and 'kept' in t, t)
        check('the slip is still filled in and Create order works again', 'Slip Test Guest' in await pg.inner_text('#sl-st-1') and await pg.locator('[data-act="n-submit"]:not([disabled])').count() == 1)
        await ctx.close()

        # Delivery
        ctx, pg, errs = await newpage(b)
        await js(pg, '[data-act="n-cell"][data-v="cheesecake|8"]'); await nxt(pg); await pg.fill('#n-name', 'Delivery Guest'); await nxt(pg)
        await pg.fill('#n-phone', '912 0098'); await pg.wait_for_timeout(450); await js(pg, '[data-act="sl-opt"][data-v="yes"]'); await nxt(pg)
        await js(pg, '[data-act="n-method"][data-v="delivery"]'); await js(pg, '#sl-st-3 .ccs-datechips [data-act="n-date"]:not(.ccs-chip-soon)')
        await js(pg, '[data-act="n-zone"][data-v="Denarau"]'); await pg.fill('#n-address', 'Room 214, Sheraton Denarau'); await js(pg, '#sl-st-3 [data-act="n-time"][data-v="15:00"]'); await nxt(pg)
        s = await pg.inner_text('#ccs-slipform')
        check('delivery written on the slip with the fee in the price', 'Delivery to Denarau, Room 214' in s and '$110' in s and 'Step 5' in await stage(pg), s[:400])
        await ctx.close()

        # Unfinished slip comes back
        ctx, pg, errs = await newpage(b)
        await js(pg, '[data-act="n-cell"][data-v="red-velvet|6"]'); await nxt(pg); await pg.fill('#n-name', 'Kept Guest'); await pg.wait_for_timeout(200)
        await pg.reload(); await pg.wait_for_timeout(700)
        await pg.evaluate("(function(){var e=[].slice.call(document.querySelectorAll('[data-tab=new]')).pop(); e&&e.click()})()"); await pg.wait_for_timeout(400)
        check('unfinished slip comes back at the same step', 'Step 2 of 8' in await stage(pg) and await pg.input_value('#n-name') == 'Kept Guest')
        await ctx.close()

        # Phone
        ctx, pg, errs = await newpage(b, PHONE)
        wide = await pg.evaluate("document.documentElement.scrollWidth <= innerWidth + 1")
        check('phone: no sideways scroll, price table fits', wide)
        await js(pg, '[data-act="n-cell"][data-v="cheesecake|8"]'); await nxt(pg)
        await pg.focus('#n-name'); await pg.wait_for_timeout(200)
        vis = await pg.evaluate("(function(){var f=document.getElementById('n-name').getBoundingClientRect(), n=document.querySelector('.ccs-nav').getBoundingClientRect(); return f.bottom <= n.top || getComputedStyle(document.querySelector('.ccs-nav')).display==='none'})()")
        check('phone: the field being typed in is not covered by the menu', vis)
        await pg.screenshot(path=str(OUT / 'phone-step2.png'))
        await ctx.close()

        ctx, pg, errs = await newpage(b, role='kitchen')
        check('kitchen login has no New order', await pg.locator('[data-tab="new"]').count() == 0)
        await ctx.close()
        await b.close()
    print(f'{sum(R)}/{len(R)} passed')
asyncio.run(main())
