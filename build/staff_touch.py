"""Corner Café Service Hub: the Jack's Restaurants touch-friendly interface standard (21 October 2026).

Roneel, 3:18 PM: "Apply the Jack's Restaurants touch-friendly interface standard to this app ... Preview first; only go
live when I say "deploy". Visual only: do not change any data, business rules or workflows." Plan confirmed 4:07 PM
("Yes, build the preview"), going out in one release with practice mode, the colleague voice and the order labels.

Base: dist/app/staff-practice-manifest.json (live old orders + colleague voice + order labels + practice mode) unless
BASE names another manifest; OUT names the manifest written (default dist/app/staff-touch-manifest.json).
The bundle becomes: the base, unchanged, then
  - src/staff.touch.js (phones: New order in the bottom menu, drag handle closes a bottom sheet; the website's reveal
    animation kept off the app; touch styles kept last);
  - the style elements ccs-touch-text (src/staff.touch-text.css, generated by build/touch_text.py) and ccs-touch
    (src/staff.touch.css: tokens, controls, iPad menu, pop-ups, phones, website page fixes).
Nothing in the base is replaced, so computers are unchanged: every new rule sits inside the tablet or phone conditions.
"""
import base64, hashlib, json, os, subprocess, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = os.environ.get('BASE', 'dist/app/staff-practice-manifest.json')
OUT = os.environ.get('OUT', 'dist/app/staff-touch-manifest.json')
bm = json.loads((ROOT / BASE).read_text())
s = (ROOT / bm['file']).read_text()


def sri(text):
    return 'sha384-' + base64.b64encode(hashlib.sha384(text.encode()).digest()).decode()


assert sri(s) == bm['sri'], 'Base does not match its manifest'
assert 'CCTouch' not in s, 'Base already has the touch standard'
js = (ROOT / 'src/staff.touch.js').read_text()
text_css = (ROOT / 'src/staff.touch-text.css').read_text()
css = (ROOT / 'src/staff.touch.css').read_text()
for part in (js, text_css, css):
    assert '</script' not in part.lower() and '</style' not in part.lower()
style = ('(function(){var h=document.head||document.documentElement;[["ccs-touch-text",%s],["ccs-touch",%s]].forEach(function(x){'
         'var s=document.getElementById(x[0]);if(!s){s=document.createElement("style");s.id=x[0];h.appendChild(s)}s.textContent=x[1]})})();\n'
         % (json.dumps(text_css), json.dumps(css)))
s = s + '\n' + js + '\n' + style

with tempfile.NamedTemporaryFile('w', suffix='.js', delete=False) as tmp:
    tmp.write(s)
subprocess.run(['node', '--check', tmp.name], check=True)
raw = s.encode()
name = 'staff-app.' + hashlib.sha256(raw).hexdigest()[:10] + '.js'
(ROOT / 'dist/app' / name).write_bytes(raw)
m = {'file': 'dist/app/' + name, 'sri': sri(s), 'bytes': len(raw), 'base': bm['file'], 'base_sri': bm['sri']}
(ROOT / OUT).write_text(json.dumps(m, indent=2) + '\n')
print(json.dumps(m))
