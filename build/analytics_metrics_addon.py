# Builds src/staff.analytics-metrics.js: the corrected Overview cards (seasonal-demand-staging.js) and Today's insights
# (staff.analytics-insights.js), delivered through the order-tools loader. The page footer still loads the older copies
# from a pinned commit; this add-on installs the corrected ones and stops the older copies from replacing them.
# Source of truth stays in the two original files. Run: python3 build/analytics_metrics_addon.py
import os
root = os.path.join(os.path.dirname(__file__), '..', 'src')
a = open(os.path.join(root, 'seasonal-demand-staging.js')).read()
b = open(os.path.join(root, 'staff.analytics-insights.js')).read()
out = """/* Corner Café Service Hub: corrected analytics definitions (27 Oct 2026). GENERATED by build/analytics_metrics_addon.py
   from src/seasonal-demand-staging.js and src/staff.analytics-insights.js. Edit those files, then rebuild. */
(function (win) {
  'use strict';
  if (win.__ccAnalyticsMetrics20261027) return;
  win.__ccAnalyticsMetrics20261027 = true;
  // hold the corrected versions: a later copy of the older files cannot replace them
  function lock(name) {
    var mine = win[name];
    try { Object.defineProperty(win, name, { configurable: true, enumerable: true, get: function () { return mine; }, set: function () {} }); } catch (e) {}
  }
  function clear(name) { try { if (Object.getOwnPropertyDescriptor(win, name)) delete win[name]; } catch (e) { win[name] = undefined; } }
  clear('CCCakeSeasonalStage'); clear('CCCakeInsights');
""" + a + "\n" + b + """
  lock('CCCakeSeasonalStage'); lock('CCCakeInsights'); lock('CCCakeMetrics');
})(window);
"""
open(os.path.join(root, 'staff.analytics-metrics.js'), 'w').write(out)
print('wrote', len(out))
