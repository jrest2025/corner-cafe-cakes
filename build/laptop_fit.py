"""Laptop fit (8 November 2026): writes src/staff.laptop.css from build/laptop-harvest.json.

Roneel, 4:50 AM: "on my laptop the details look so large and requires scrolls"; 4:59 AM: "the dashboards must be
optimised for laptop with texts not so very big"; 5:01 AM: "yes please".
His laptop shows the app 1512 x 862 with a trackpad. The app's sizes were set for tablets and big screens, so on a laptop
text and controls are a step too big and forms need scrolling.

build/laptop-harvest.json lists, for every visible text (15px and up) and control (40px and taller) on every screen,
New order step and order pop-up at 1512 x 860, the rule that sets its size (collected in the replica with Chrome's own
style matching). Each one gets a matching rule for laptops only, one step smaller:
  text: 15px -> 14px; 16px and up -> 86% (16 -> 14, 18 -> 15.5, 20 -> 17, 24 -> 20.5, 28 -> 24), never under 14px
  controls 40 to 72px tall -> 80% (44 -> 35, 48 -> 38, 56 -> 45, 64 -> 51), never under 34px
Laptops only: (hover: hover) and (pointer: fine) and (min-width: 1100px) and (max-width: 1700px), so phones, iPads and big
screens stay exactly as they are. Each new rule repeats the old selector with "html" in front (one step more specific) and the old
rule's own importance, inside the old rule's own media conditions, so it applies exactly where
the old one did, wins over it, and still loses to the rules that were already beating it. Text under 15px, chart
drawing (SVG) and the bars of the Cake Pulse chart are not touched.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
H = json.loads((ROOT / 'build/laptop-harvest.json').read_text())
LAP = '(hover: hover) and (pointer: fine) and (min-width: 1100px) and (max-width: 1700px)'
PRE = ':not(.cc-lp0)'


def parts(sel):
    out, depth, cur = [], 0, ''
    for ch in sel:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def boost(p):
    # One step more specific than the old selector, and no more: an extra type (html) in front, so the new rule wins
    # where the old one won and still loses to every rule that was more specific than the old one.
    if p.startswith(':root'):
        return 'html' + p
    if re.match(r'^html\b', p):
        m = re.match(r'^(html)((?:[.:#\[][^\s>+~]*)?)(.*)$', p, re.S)
        return m.group(1) + m.group(2) + PRE + m.group(3)
    return 'html ' + p


def text_px(px):
    if px < 15.5:
        return 14
    return max(14, round(px * 0.86 * 2) / 2)


rules, seen = [], set()
for r in H:
    if r['sel'] in ('INHERITED', 'INLINE'):
        continue
    imp = '!important' if re.search(r'!\s*important', r['val']) else ''
    val = re.sub(r'\s*!\s*important\s*$', '', r['val'].strip())
    comp = float(re.sub(r'px$', '', r['computed'])) if r['computed'].endswith('px') else None
    if comp is None:
        continue
    if r['prop'] == 'font-size':
        if comp < 15:
            continue
        t = text_px(comp)
        decl = 'font-size:%s' % (('min(%s,%gpx)' % (val, t)) if re.search(r'vw|vh|clamp|min\(|max\(|var\(', val) else '%gpx' % t) + imp
    else:
        m = re.match(r'^([\d.]+)px$', val)
        if not m or not (40 <= float(m.group(1)) <= 72):
            continue
        decl = '%s:%dpx' % (r['prop'], max(34, round(float(m.group(1)) * 0.8))) + imp
    sel = ', '.join(boost(p) for p in parts(r['sel']))
    key = (sel, decl, tuple(r['media']))
    if key in seen:
        continue
    seen.add(key)
    rule = sel + '{' + decl + '}'
    for md in reversed(r['media']):
        rule = '@media %s{%s}' % (md, rule)
    rules.append(rule)

head = ('/* Laptop fit (8 November 2026). GENERATED by build/laptop_fit.py from build/laptop-harvest.json: do not edit by hand.\n'
        '   %d rules: text and controls one step smaller on laptops only. Hand-written layout rules follow in src/staff.laptop-layout.css. */\n') % len(rules)
out = head + '@media %s{\n%s\n}\n' % (LAP, '\n'.join(rules))
(ROOT / 'src/staff.laptop.css').write_text(out)
print(len(rules), 'rules', len(out), 'bytes')
